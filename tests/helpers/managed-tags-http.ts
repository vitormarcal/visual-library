import assert from 'node:assert/strict'
import { createServer } from 'node:http'
import { readFile } from 'node:fs/promises'
import { createApp, createRouter, defineEventHandler, getRouterParam, toNodeListener } from 'h3'
Object.assign(globalThis, { defineEventHandler, getRouterParam, useRuntimeConfig: () => ({ public: { maxImageSizeBytes: 1048576 } }) })
const { ensureDataStore, getImageTags, replaceImageTags, addTagsToImages, deleteImageRecord } = await import('../../server/db.ts')
const db = await ensureDataStore()
const router = createRouter()
router.post('/api/assets', (await import('../../server/api/assets.post.ts')).default)
router.put('/api/assets/:id/references/tags', (await import('../../server/api/assets/[id]/references/tags.put.ts')).default)
const server = createServer(toNodeListener(createApp().use(router)))
await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve))
const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`
const png = await readFile(new URL('../fixtures/images/tiny.png', import.meta.url))
const names = (id: string) => getImageTags(id).map(tag => tag.name)
const group = (id: string, entity: string) => db.prepare('SELECT tags_json, revision FROM asset_reference_tag_groups WHERE asset_id = ? AND entity_id = ?').get(id, entity)
const upload = async (entity: string, tags: string[], movements?: string[], revision = 1) => {
  const body = new FormData()
  body.append('image', new Blob([png]), 'test.png'); body.append('source', 'media-pulse')
  body.append('tags', JSON.stringify(tags)); body.append('sourceReference', JSON.stringify({ entityType: 'artwork', entityId: entity }))
  if (movements) body.append('managedTags', JSON.stringify({ movements: { tags: movements, revision } }))
  return fetch(base + '/api/assets', { method: 'POST', body })
}
const update = (id: string, entity: string, tags: string[], revision: number) => fetch(base + `/api/assets/${id}/references/tags`, {
  method: 'PUT', headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ application: 'media-pulse', entityType: 'artwork', entityId: entity, group: 'movements', tags, revision }),
})
try {
  const first = await upload('7', ['The Kiss', 'Klimt'], ['Art Nouveau', 'Simbolismo'])
  assert.equal(first.status, 201); const asset = await first.json(); const id = asset.id
  assert.deepEqual(asset.sourceReferences[0].managedTags.movements, { tags: ['Art Nouveau','Simbolismo'], revision:1 })
  replaceImageTags(id, [...names(id), 'Favoritos'])
  assert.equal((await upload('8', [], ['Simbolismo'])).status, 200)
  const corrected = await update(id,'7',['Secessão Vienense'],2)
  assert.equal(corrected.status,200); assert.deepEqual((await corrected.json()).preservedTags,['Simbolismo'])
  assert.deepEqual(new Set(names(id)),new Set(['The Kiss','Klimt','Favoritos','Simbolismo','Secessão Vienense']))
  assert.equal((await update(id,'8',[],2)).status,200)
  assert.equal(names(id).includes('Simbolismo'),false)
  addTagsToImages([id], ['Secessão Vienense'])
  assert.equal((await update(id,'7',['Realismo'],3)).status,200)
  assert.equal(names(id).includes('Secessão Vienense'),true)
  replaceImageTags(id,names(id).filter(name=>name!=='Realismo'))
  assert.equal((await update(id,'7',['Realismo','Cubismo'],4)).status,200)
  assert.equal(names(id).includes('Realismo'),false)
  assert.equal(names(id).includes('Cubismo'),true)
  assert.equal((await update(id,'7',['Realismo','Cubismo'],4)).status,200)
  assert.equal(names(id).includes('Realismo'),false)
  const before = JSON.stringify(group(id,'7'))
  assert.equal((await update(id,'7',['Realismo'],3)).status,409)
  assert.equal((await update(id,'7',['Different'],4)).status,409)
  assert.equal(JSON.stringify(group(id,'7')),before)
  replaceImageTags(id,Array.from({length:8},(_,i)=>`personal ${i}`))
  const full = names(id)
  assert.equal((await update(id,'7',['Cubismo','Dadaísmo'],5)).status,200)
  assert.equal(names(id).length,9); assert.equal(names(id).includes('Cubismo'),false)
  assert.equal(names(id).includes('Dadaísmo'),true)
  assert.equal((await update(id,'7',['x'.repeat(49)],6)).status,409)
  assert.equal((await update(id,'missing',[],1)).status,404)
  replaceImageTags(id,['personal'])
  const rollback = JSON.stringify(group(id,'7'))
  db.exec("CREATE TRIGGER fail_group BEFORE UPDATE ON asset_reference_tag_groups BEGIN SELECT RAISE(ABORT, 'test group failure'); END")
  assert.equal((await update(id,'7',['Cubismo','Futurismo'],6)).status,500)
  assert.equal(JSON.stringify(group(id,'7')),rollback); assert.deepEqual(names(id),['personal'])
  db.exec('DROP TRIGGER fail_group')
  assert.equal((await upload('legacy', ['Impressionismo'])).status,200)
  const legacy = await update(id,'legacy',['Expressionismo'],1)
  assert.equal(legacy.status,200); assert.equal((await legacy.json()).legacyTagsPreserved,true)
  assert.equal(names(id).includes('Impressionismo'),true)
  const personalBefore = names(id)
  assert.equal((await upload('9', [], ['x'.repeat(49)])).status,409)
  assert.deepEqual(names(id),personalBefore)
  assert.equal(db.prepare("SELECT 1 FROM asset_references WHERE entity_id = '9'").get(),undefined)
  const bad = await fetch(base+`/api/assets/${id}/references/tags`,{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({application:'media-pulse',entityType:'artwork',entityId:7,group:'movements',tags:[],revision:1})})
  assert.equal(bad.status,400)
  deleteImageRecord(id)
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM asset_reference_tag_groups WHERE asset_id = ?').get(id)!.n,0)
  console.log('Managed classification HTTP, provenance, limits, revision and rollback assertions passed')
} finally { server.closeAllConnections(); await new Promise<void>(resolve=>server.close(()=>resolve())); db.close() }
